#!/bin/sh
# Dump MAX9296A register ranges (auto-increment block reads) as "addr val" lines.
for rng in 0x0000:0x40 0x0040:0x40 0x0100:0x40 0x0140:0x20 0x01f0:0x80 0x02b0:0x20 0x0300:0x40 0x0400:0x100 0x0500:0x40 0x0b00:0x40 0x0b80:0x20 0x0c00:0x40 0x0c80:0x20 0x0f00:0x08 0x1c00:0x10 0x1d00:0x10; do
  a=${rng%:*}; n=${rng#*:}; off=0
  while [ $off -lt $((n)) ]; do
    c=$(( n - off > 32 ? 32 : n - off )); x=$((a+off))
    v=$(i2ctransfer -f -y 10 w2@0x48 $(printf "0x%02x 0x%02x" $((x>>8)) $((x&255))) r$c 2>/dev/null) || v=""
    i=0; for b in $v; do printf "0x%04x %s\n" $((x+i)) $b; i=$((i+1)); done
    off=$((off+c))
  done
done
